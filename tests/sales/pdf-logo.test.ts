import { describe, expect, it } from "vitest";
import sharp from "sharp";

import { logoBufferForPdf } from "@/modules/sales/application/pdf-logo";

const PNG_BYTES = Uint8Array.from([
  0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d,
  0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
  0x08, 0x06, 0x00, 0x00, 0x00, 0x1f, 0x15, 0xc4, 0x89, 0x00, 0x00, 0x00,
  0x0a, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9c, 0x63, 0x00, 0x01, 0x00, 0x00,
  0x05, 0x00, 0x01, 0x0d, 0x0a, 0x2d, 0xb4, 0x00, 0x00, 0x00, 0x00, 0x49,
  0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
]);

describe("logoBufferForPdf", () => {
  it("passes JPEG and PNG through for pdfkit", async () => {
    const png = await logoBufferForPdf({
      bytes: PNG_BYTES,
      contentType: "image/png",
    });
    expect(png).toEqual(Buffer.from(PNG_BYTES));
  });

  it("converts WebP to PNG so export matches the HTML preview", async () => {
    const webp = await sharp(PNG_BYTES).webp().toBuffer();
    const buffer = await logoBufferForPdf({
      bytes: webp,
      contentType: "image/webp",
    });
    expect(buffer).not.toBeNull();
    expect(buffer?.subarray(0, 8)).toEqual(
      Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])
    );
  });

  it("returns null for types pdfkit cannot embed", async () => {
    await expect(
      logoBufferForPdf({ bytes: PNG_BYTES, contentType: "image/gif" })
    ).resolves.toBeNull();
  });
});
